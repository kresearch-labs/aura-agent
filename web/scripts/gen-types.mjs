#!/usr/bin/env node
// Gen-types.mjs — json-schema-to-typescript over the hub's declared JSON shapes. The Teams
// hub's schema source of truth is the Python code; for now this reads a hand-checked
// `api/schema.json` (a copy of the hub's JSON shapes as the routes answer today) and writes
// src/lib/api/types.ts. Keep the hand-filled schema in sync with the hub when a route changes.
import { mkdirSync, readFileSync, writeFileSync } from "fs";
import { compile } from "json-schema-to-typescript";

const src = JSON.parse(readFileSync(new URL("../api/schema.json", import.meta.url), "utf-8"));

mkdirSync(new URL("../src/lib/api", import.meta.url), { recursive: true });
let out = "// generated by scripts/gen-types.mjs — do not edit\n\n";
for (const [name, shape] of Object.entries(src)) {
  out += (await compile(shape, name, { bannerComment: "" })).replace(/\n+/g, "\n") + "\n";
}
writeFileSync(new URL("../src/lib/api/types.ts", import.meta.url), out);
console.log(`wrote types for ${Object.keys(src).length} shapes`);
